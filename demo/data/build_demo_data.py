"""Assemble browser-safe demo data from reusable public source CSVs."""
from __future__ import annotations

import csv
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
DEMO = HERE.parent
POPULATION = HERE / "population_2026-10.csv"
AGE_POPULATION = HERE / "ine_ecp_2026_mujeres_40_79_edad.csv"
RULES = HERE.parent.parent / "datos_territoriales" / "reglas_cribado_2026-11.csv"
MADRID = HERE / "madrid_context_2025_ccaa.csv"
OUTPUT = DEMO / "data.js"


def read_rows(path: Path, *, delimiter: str = ",") -> list[dict[str, str]]:
    with path.open(encoding="utf-8-sig", newline="") as source:
        return list(csv.DictReader(source, delimiter=delimiter))


def build() -> dict:
    population = read_rows(POPULATION)
    territories = []
    national = None
    for row in population:
        bands = {band: int(row[band]) for band in ("45_49", "50_69", "70_74")}
        if row["code"] == "00":
            national = bands
            continue
        territories.append({"code": row["code"], "name": row["territory"], "bands": bands})
    if len(territories) != 19 or national is None:
        raise ValueError("Expected 19 territorial rows plus the national total")

    age_rows = read_rows(AGE_POPULATION)
    age_counts: dict[str, dict[str, int]] = {}
    age_keys: set[tuple[str, str]] = set()
    for row in age_rows:
        if row["periodo"] != "1 de octubre de 2026":
            continue
        code_match = re.match(r"^(\d{2})", row["territorio"])
        if not code_match:
            continue
        code = code_match.group(1)
        key = (code, row["edad"])
        if key in age_keys:
            raise ValueError(f"Duplicate age count for territory {code}, age {row['edad']}")
        age_keys.add(key)
        if int(row["mujeres_residentes"]) < 0 or not 40 <= int(row["edad"]) <= 79:
            raise ValueError(f"Invalid age-count row for territory {code}, age {row['edad']}")
        age_counts.setdefault(code, {})[row["edad"]] = int(row["mujeres_residentes"])
    expected_codes = {row["code"] for row in territories}
    expected_ages = {str(age) for age in range(40, 80)}
    if (set(age_counts) != expected_codes
            or any(set(ages) != expected_ages for ages in age_counts.values())):
        raise ValueError("Expected 40 single-year ages (40–79) for each of 19 territories")
    for territory in territories:
        ages = age_counts[territory["code"]]
        derived_50_69 = sum(ages[str(age)] for age in range(50, 70))
        derived_45_74 = sum(ages[str(age)] for age in range(45, 75))
        bands = territory["bands"]
        if derived_50_69 != bands["50_69"] or derived_45_74 != sum(bands.values()):
            raise ValueError(f"Single-age population does not reconcile for territory {territory['code']}")
    rules = read_rows(RULES)
    if len(rules) != 19:
        raise ValueError("Expected exactly 19 territorial rule records")
    rule_by_code = {row["codigo_territorio"]: row for row in rules}
    if set(rule_by_code) != expected_codes:
        raise ValueError("Territorial rules must contain exactly one record for each demographic territory")
    for row in rules:
        if row["uso_escenario"] not in {"si", "no"}:
            raise ValueError(f"Invalid scenario-usage flag for territory {row['codigo_territorio']}")
        scenario_ages = (row["edad_min_escenario"], row["edad_max_escenario"])
        if row["uso_escenario"] == "si":
            if not all(scenario_ages) or not row["fuente_oficial"] or not row["estado_vigencia"]:
                raise ValueError(f"Scenario range lacks current-evidence fields for territory {row['codigo_territorio']}")
            age_min, age_max = map(int, scenario_ages)
            if not 40 <= age_min <= age_max <= 79:
                raise ValueError(f"Scenario age range outside INE extract for territory {row['codigo_territorio']}")
        elif any(scenario_ages):
            raise ValueError(f"Disabled scenario must not carry a calculated range for territory {row['codigo_territorio']}")
    for territory in territories:
        code = territory["code"]
        territory["ageCounts"] = age_counts[code]
        territory["screeningRule"] = rule_by_code[code]

    madrid_rows = read_rows(MADRID, delimiter=";")
    madrid_row = next(row for row in madrid_rows if row["territorio"] == "Comunidad de Madrid")
    madrid_2025 = {band: int(madrid_row[f"mujeres_{band}"])
                   for band in ("45_49", "50_69", "70_74")}
    data = {
        "referenceDate": "1 de octubre de 2026",
        "referenceDateISO": "2026-10-01",
        "status": "provisional",
        "territories": territories,
        "national": national,
        "madrid2025": madrid_2025,
        "municipalities": int(madrid_row["municipios"]),
        "territorialRulesCutoff": "2026-11-22",
    }
    OUTPUT.write_text(
        "// Generated by demo/data/build_demo_data.py from the adjacent source CSV files.\n"
        "const CRABI_DATA = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n"
        "if (typeof module !== 'undefined' && module.exports) module.exports = CRABI_DATA;\n",
        encoding="utf-8",
    )
    return data


if __name__ == "__main__":
    result = build()
    print(f"Wrote {OUTPUT.name}: {len(result['territories'])} territories; {result['referenceDate']} ({result['status']}).")
